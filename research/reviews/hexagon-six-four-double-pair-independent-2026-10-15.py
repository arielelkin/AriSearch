#!/usr/bin/env python3
"""Independent full double-pair audit; standard library, no producer imports.
Builds stars from directed corner-port cycles, enumerates all supports, checks
retained rational identities and explicitly glues each four-face torus.
"""
from collections import Counter, defaultdict
from fractions import Fraction
from itertools import combinations, permutations, product
from pathlib import Path
import json

ROOT = Path(__file__).resolve().parents[2]
CERT = ROOT / "research/certificates/hexagon-six-four-double-pair-certificate-2026-10-15.json"
A = tuple(range(6))
ALL = (1 << 12) - 1


def bracelet(word):
    rotations = []
    for order in (word, word[::-1]):
        rotations.extend(order[i:] + order[:i] for i in range(6))
    return min(rotations)


def domain(private):
    alphabet = sorted(set(A) - set(private))
    raw = set()
    for repeated in combinations(alphabet, 2):
        multiset = tuple(alphabet) + repeated
        raw.update(permutations(multiset))
    assert len(raw) == 1080
    words = {bracelet(w) for w in raw}
    assert len(words) == 96
    return sorted(words)


def local_data(B):
    # Port: native corner, left length, right length, far-left corner,
    # far-right corner. Distinct occurrences with equal labels remain distinct.
    ports = []
    for typ, word in enumerate((A, B)):
        base = 6 * typ
        for corner in range(6):
            sides = (corner, (corner + 1) % 6)
            fars = (base + (corner - 1) % 6, base + (corner + 1) % 6)
            for orientation in (0, 1):
                ports.append((base + corner, word[sides[orientation]],
                              word[sides[1-orientation]], fars[orientation],
                              fars[1-orientation]))
    by_left = defaultdict(list)
    for port in ports:
        by_left[port[1]].append(port)
    states = defaultdict(set)
    # All ORDERED cyclic port triples, including repeated corner occurrences.
    for a in ports:
        for b in by_left[a[2]]:
            for c in by_left[b[2]]:
                if c[2] != a[1]:
                    continue
                star = tuple(sorted((a[0], b[0], c[0])))
                pairs = tuple(sorted((tuple(sorted((a[4], b[3]))),
                                      tuple(sorted((b[4], c[3]))),
                                      tuple(sorted((c[4], a[3]))))))
                states[star].add(pairs)
    stars = sorted(states)
    # Pair membership is generated by choosing actual positions in a star,
    # so repeated pair indices require two occurrences, not mere set membership.
    containing = defaultdict(int)
    for i, star in enumerate(stars):
        for p, q in combinations(range(3), 2):
            containing[tuple(sorted((star[p], star[q])))] |= 1 << i
    options = [tuple(tuple(containing[pair] for pair in state)
                     for state in states[star]) for star in stars]
    active = (1 << len(stars)) - 1
    while True:
        next_active = 0
        for i, modes in enumerate(options):
            if active >> i & 1 and any(all(active & far for far in mode)
                                     for mode in modes):
                next_active |= 1 << i
        if next_active == active:
            break
        active = next_active
    pruned = [star for i, star in enumerate(stars) if active >> i & 1]
    return stars, states, pruned


def closed_covers(stars, states):
    n = len(stars)
    assert n <= 12
    cover = [sum(1 << c for c in set(star)) for star in stars]
    containing = defaultdict(int)
    for i, star in enumerate(stars):
        for p, q in combinations(range(3), 2):
            containing[tuple(sorted((star[p], star[q])))] |= 1 << i
    options = [tuple(tuple(containing[pair] for pair in state)
                     for state in states[star]) for star in stars]
    result = set()
    for subset in range(1 << n):
        covered = 0
        indices = [i for i in range(n) if subset >> i & 1]
        for i in indices:
            covered |= cover[i]
        if covered != ALL:
            continue
        if all(any(all(subset & far for far in mode) for mode in options[i])
               for i in indices):
            result.add(tuple(stars[i] for i in indices))
    return result


def torus_check(B, chosen, ring):
    shared = [x for x in A if x in set(B)]
    # Shared order around A determines the common square and its two-coloring.
    bits = {x: j % 2 for j, x in enumerate(shared)}
    b_order = [B[i] for i in range(6) if i in chosen]
    same = any(b_order == shared[j:] + shared[:j] for j in range(4))
    opposite = any(b_order == list(reversed(shared))[j:] + list(reversed(shared))[:j]
                   for j in range(4))
    assert same != opposite
    # If common orders are the same, reflect B and traverse its native indices
    # in reverse. Native corner angles remain attached to their original slots.
    reverse_b = same
    pairings = []
    for side in set(A) - set(B):
        pairings.append(((0, side), (1, side)))
    for side in set(range(6)) - set(chosen):
        pairings.append(((2, side), (3, side)))
    for side in chosen:
        length = B[side]
        for parity in (0, 1):
            pairings.append(((parity, length), (2 + (parity ^ bits[length]), side)))
    assert len(pairings) == 12
    used = Counter(edge for pair in pairings for edge in pair)
    assert used == Counter(product(range(4), range(6)))
    links = defaultdict(list)
    face_adj = defaultdict(set)
    def endpoints(face, side):
        pair = ((side-1) % 6, side)
        if face >= 2 and reverse_b:
            pair = pair[::-1]
        return tuple(6*face + corner for corner in pair)
    for (f, s), (g, t) in pairings:
        assert (A if f < 2 else B)[s] == (A if g < 2 else B)[t]
        e, h = endpoints(f, s), endpoints(g, t)
        for v, w in ((e[0], h[1]), (e[1], h[0])):
            links[v].append(w)
            links[w].append(v)
        face_adj[f].add(g)
        face_adj[g].add(f)
    assert all(len(links[v]) == 2 for v in range(24))
    components = []
    unseen = set(range(24))
    while unseen:
        stack = [min(unseen)]
        component = set()
        while stack:
            v = stack.pop()
            if v in component:
                continue
            component.add(v)
            stack.extend(links[v])
        unseen -= component
        assert len(component) == 3
        components.append(tuple(sorted((v % 6) + (0 if v // 6 < 2 else 6)
                                       for v in component)))
    assert Counter(components) == Counter({star: 2 for star in ring})
    assert len(components) - 12 + 4 == 0
    seen, stack = set(), [0]
    while stack:
        f = stack.pop()
        if f not in seen:
            seen.add(f)
            stack.extend(face_adj[f])
    assert seen == set(range(4))


def formal_rings(B):
    found = set()
    choices = 0
    for chosen in product(*(tuple(i for i, y in enumerate(B) if y == x)
                             for x in sorted(set(B)))):
        chosen = frozenset(chosen)
        words = (tuple(("shared", x) if x in set(B) else ("A", x) for x in A),
                 tuple(("shared", x) if i in chosen else ("B", i)
                       for i, x in enumerate(B)))
        edges = defaultdict(list)
        for typ, word in enumerate(words):
            for j in range(6):
                edges[frozenset((word[j], word[(j+1) % 6]))].append(6*typ+j)
        if len(edges) != 12 or any(len(v) != 1 for v in edges.values()):
            continue
        triangles = []
        for labels in combinations(set(words[0]) | set(words[1]), 3):
            pairs = [frozenset(pair) for pair in combinations(labels, 2)]
            if all(pair in edges for pair in pairs):
                triangles.append(tuple(sorted(edges[pair][0] for pair in pairs)))
        if len(triangles) != 4 or Counter(c for t in triangles for c in t) != Counter(range(12)):
            continue
        ring = tuple(sorted(triangles))
        torus_check(B, chosen, ring)
        found.add(ring)
        choices += 1
    return found, choices


def star_row(star):
    return tuple(Fraction(star.count(i)) for i in range(12)) + (Fraction(-2),)


def row_check(cert, rings, support):
    assert tuple(sorted(tuple(s) for s in cert["source_stars"])) == support
    target = tuple(sorted(tuple(s) for s in cert["ring"]))
    assert target in rings
    rows = [tuple(Fraction(i < 6) for i in range(12)) + (Fraction(-4),),
            tuple(Fraction(i >= 6) for i in range(12)) + (Fraction(-4),)]
    rows.extend(star_row(s) for s in cert["source_stars"])
    assert len(cert["row_combinations"]) == 4
    for target_star, coeffs in zip(cert["ring"], cert["row_combinations"]):
        scalars = list(map(Fraction, coeffs))
        assert len(scalars) == len(rows)
        actual = tuple(sum(c * row[j] for c, row in zip(scalars, rows)) for j in range(13))
        assert actual == star_row(target_star)


def main():
    retained = json.loads(CERT.read_text())
    assert retained["schema"] == "HEXAGON_A6_B2211_ALL_SHARED_V1"
    assert retained["domain"]["raw_words"] == 2160
    assert retained["domain"]["cyclic_words"] == 192
    records = {}
    case_stats = {}
    for case in retained["cases"]:
        private = tuple(case["A_private"])
        assert private not in case_stats
        case_stats[private] = case["statistics"]
        assert case["raw_words"] == 1080 and case["cyclic_words"] == 96
        for r in case["records"]:
            key = private, tuple(r["B"])
            assert key not in records
            records[key] = r
    assert set(case_stats) == {(0, 2), (0, 3)}
    reached = set()
    totals = Counter()
    summaries = []
    total_statistics = Counter()
    for private in ((0, 2), (0, 3)):
        stats = Counter()
        for B in domain(private):
            totals["cyclic_words"] += 1
            initial, states, pruned = local_data(B)
            if set(c for s in initial for c in s) != set(range(12)):
                stats["missing_initial_corner"] += 1
                assert (private, B) not in records
                continue
            if set(c for s in pruned for c in s) != set(range(12)):
                stats["missing_pruned_corner"] += 1
                assert (private, B) not in records
                continue
            covers = closed_covers(pruned, states)
            r = records[(private, B)]
            reached.add((private, B))
            assert initial == [tuple(s) for s in r["initial_stars"]]
            assert pruned == [tuple(s) for s in r["pruned_stars"]]
            assert set(r["microstates_far_pairs"]) == {",".join(map(str, st)) for st in initial}
            for star in initial:
                key = ",".join(map(str, star))
                expected = {tuple(tuple(pair) for pair in assignment)
                            for assignment in r["microstates_far_pairs"][key]}
                assert states[star] == expected
            rings, choices = formal_rings(B)
            assert rings == {tuple(sorted(tuple(s) for s in ring)) for ring in r["formal_rings"]}
            certified = {}
            for item in r["endpoint_closed_covers"]:
                support = tuple(sorted(tuple(s) for s in item["stars"]))
                assert support not in certified
                certified[support] = item["witness"]
            assert set(certified) == covers
            direct = span = 0
            for support in covers:
                witness = certified[support]
                if any(set(ring) <= set(support) for ring in rings):
                    assert witness["kind"] == "direct_ring"
                    ring = tuple(sorted(tuple(s) for s in witness["ring"]))
                    assert ring in rings and set(ring) <= set(support)
                    direct += 1
                else:
                    assert witness["kind"] == "rational_span"
                    row_check(witness["certificate"], rings, support)
                    span += 1
            stats["feasible_words"] += 1
            stats["closed_covers"] += len(covers)
            stats["direct_ring"] += direct
            stats["rational_span"] += span
            totals["words_with_covers"] += bool(covers)
            totals["closed_covers"] += len(covers)
            totals["direct"] += direct
            totals["row_certificates"] += span
            totals["torus_slot_choices"] += choices
            totals["largest_pruned_atlas"] = max(totals["largest_pruned_atlas"], len(pruned))
            summaries.append([list(private), list(B), len(covers), direct, span])
        assert stats == Counter(case_stats[private])
        total_statistics.update(stats)
    assert total_statistics == Counter(retained["statistics"])
    assert reached == set(records)
    assert [totals[k] for k in ("cyclic_words", "words_with_covers", "closed_covers", "direct", "row_certificates", "largest_pruned_atlas")] == [192, 24, 93, 71, 22, 12]
    print(json.dumps({"status": "PASS", "linear_words": 2160,
                      "totals": dict(totals), "rows": summaries}, sort_keys=True))

if __name__ == "__main__":
    main()
