"""Exact geometry, circular links and translational holonomy of eac quotient.
Read-only by default; --output explicitly retains developed certificate.
"""
import argparse,json
from pathlib import Path
from collections import defaultdict,deque
from sage.all import QuadraticField,AA,matrix,vector,identity_matrix,ZZ,lcm
K=QuadraticField(3,'w',embedding=AA(3).sqrt());w=K.gen()
I=identity_matrix(K,2)
ROT={0:I,60:matrix(K,[[K(1)/2,-w/2],[w/2,K(1)/2]]),90:matrix(K,[[0,-1],[1,0]])}
values={'a':K(1),'b':1+4*w/3,'c':w/3,'d':2+w/3,'e':1+w/3,'f':2+4*w/3,'h':1-w/3}
def coords(face):
    p=vector(K,[0,0]);v=vector(K,[1,0]);out=[]
    for i,label in enumerate(face['labels']):
        out.append(p);p=p+values[label]*v
        turn=180-face['angles'][(i+1)%len(face['angles'])]
        v=ROT[turn]*v
    assert p==vector(K,[0,0]) and v==vector(K,[1,0])
    return out

def develop(output=None):
    source=Path(__file__).parents[1]/'certificates/partial-contact-cairo-alternate-eac-eight-face-lift.json'
    r=json.loads(source.read_text());faces=r['faces'];pairs=r['paired_edges'];ps=list(map(coords,faces))
    # The circular link has one interval for each tile corner. Its endpoint
    # gluings give a connected degree2 graph in each retained vertex class.
    adj=defaultdict(list)
    for (u,i),(v,j) in pairs:
        nu,nv=len(ps[u]),len(ps[v])
        assert values[faces[u]['labels'][i]]==values[faces[v]['labels'][j]]
        for a,b in [((u,i),(v,(j+1)%nv)),((u,(i+1)%nu),(v,j))]:
            adj[a].append(b);adj[b].append(a)
    for cls in r['vertex_classes']:
        nodes=set(map(tuple,cls));assert all(len(adj[x])==2 for x in nodes)
        seen=set();todo=[next(iter(nodes))]
        while todo:
            x=todo.pop()
            if x not in seen:seen.add(x);todo+=adj[x]
        assert seen==nodes and sum(faces[u]['angles'][i] for u,i in nodes)==360
    transforms={0:(I,vector(K,[0,0]))};graph=defaultdict(list)
    for (u,i),(v,j) in pairs:graph[u].append((i,v,j));graph[v].append((j,u,i))
    def proposal(u,i,v,j):
        ru,tu=transforms[u];q=ru*(ps[u][(i+1)%len(ps[u])]-ps[u][i])
        z=ps[v][(j+1)%len(ps[v])]-ps[v][j]
        q=-q;den=z.dot_product(z);co=z.dot_product(q)/den;si=(z[0]*q[1]-z[1]*q[0])/den
        rv=matrix(K,[[co,-si],[si,co]]);assert rv.transpose()*rv==I
        tv=ru*ps[u][i]+tu-rv*ps[v][(j+1)%len(ps[v])]
        return rv,tv
    todo=deque([0])
    while todo:
        u=todo.popleft()
        for i,v,j in graph[u]:
            if v not in transforms:transforms[v]=proposal(u,i,v,j);todo.append(v)
    assert len(transforms)==len(faces)
    translations=[]
    for (u,i),(v,j) in pairs:
        rv,tv=proposal(u,i,v,j);r0,t0=transforms[v]
        assert rv==r0,'nontrivial rotational holonomy'
        translations.append(tv-t0)
    nonzero=[t for t in translations if t]
    coeffs=matrix([[z for component in t for z in component.list()] for t in nonzero]).transpose()
    assert coeffs.rank()==2
    den=lcm([x.denominator() for x in coeffs.list()]);integer=matrix(ZZ,coeffs*den)
    # Integer row HNF on the transpose preserves exactly the subgroup
    # generated by all coefficient vectors, including nonprimitive cycles.
    basisrows=integer.transpose().hermite_form(include_zero_rows=False)
    assert basisrows.nrows()==2
    lattice=[vector(K,[K([row[0]/den,row[1]/den]),K([row[2]/den,row[3]/den])]) for row in basisrows.rows()]
    covolume=abs(matrix(lattice).det())
    areas=[]
    for pts in ps:areas.append(sum(pts[i][0]*pts[(i+1)%len(pts)][1]-pts[i][1]*pts[(i+1)%len(pts)][0] for i in range(len(pts)))/2)
    assert all(a>0 for a in areas) and covolume==sum(areas)
    def enc(x):return [str(z) for z in K(x).list()]
    record={'source_quotient':source.name,'native_parameters':{k:enc(v) for k,v in values.items()},
            'reference_vertices':[[[enc(x) for x in p] for p in pts] for pts in ps],
            'face_transforms':[{'rotation':[[enc(x) for x in row] for row in transforms[u][0].rows()],
                                'translation':[enc(x) for x in transforms[u][1]]} for u in range(len(faces))],
            'seam_holonomies':[[enc(x) for x in t] for t in translations],
            'period_lattice':[[enc(x) for x in t] for t in lattice],
            'tile_areas':[enc(a) for a in areas],'covolume':enc(covolume),
            'checks':'all48sideends paired;16single circular links angle360;8facesconnected;allseamholonomy translational;rank2 integral deck lattice;covolume equals total area'}
    if output:Path(output).write_text(json.dumps(record,indent=2)+'\n')
    print('PASS exact developed eac quotient; lattice',lattice,'covolume',covolume,'areas',areas)
    return record
