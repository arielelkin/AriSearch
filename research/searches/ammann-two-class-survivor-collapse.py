#!/usr/bin/env python3
"""Exact pairwise congruence-collapse analysis for the surviving decorations.

Replay:
  conda run --no-capture-output -n arisearch python3 \
      research/searches/ammann-two-class-survivor-collapse.py TYPES.json PATCH7.json OUT.json

For each surviving (thin, thick) decoration pair (combinatorial filters of
ammann-two-class-pairs.py and the sector test passed), its generic tile
classes X_1..X_N are recomputed on the 7-fold patch.  Interior points are
free: z_j = s_j + t_j w (s_j, t_j real), j over the points used.

For every unordered pair of classes (X, Y), every choice of vertices to be
deleted as straight angles (D_X, D_Y; at least 5 corners must remain, since a
triangle/quadrilateral tile kills the pair), every cyclic shift and both
orientations (direct / mirror), the ideal in K[s, t] generated by
  * edge-proportionality  f_{k+i} e_0 - f_k e_i   (and complex conjugates),
  * unimodularity         f_k conj(f_k) - e_0 conj(e_0),
  * straightness          Im(conj(v - a)(b - v)) for every deleted v
  * non-degeneracy        u |e_0|^2 |f_k|^2 = 1 (edges cannot vanish: interior
                          points are strictly inside their rhombs)
is computed (Singular Groebner basis over K = Q(w)).  These are necessary
conditions for X ~ Y (mirror allowed) with the stated degenerations.  The
record lists, per class pair, every non-empty ideal (with its dimension and,
when zero-dimensional, its real points and whether the remaining exact
inequalities -- weak convexity of every class, nonzero edges -- hold there).

A two-class collapse requires a partition of {X_i} into <= 2 groups with all
members of a group congruent; the record then checks whether the class graph
whose edges are the pairs with an admissible congruence point can be covered
by <= 2 cliques with a common parameter point.
"""
import sys, json, itertools, importlib.util, os
from sage.all import (CyclotomicField, PolynomialRing, QQbar, AA, QQ, binomial)

here = os.path.dirname(os.path.abspath(__file__))
spec = importlib.util.spec_from_file_location('pa', os.path.join(here, 'ammann-two-class-pairs.py'))
pa = importlib.util.module_from_spec(spec); spec.loader.exec_module(pa)

K = CyclotomicField(10); w = K.gen()
emb = K.hom([QQbar.zeta(10)])
wq = QQbar.zeta(10)
Iq = QQbar(-1).sqrt()

def Kel(t):
    return t[0] + t[1] * w + t[2] * w**2 + t[3] * w**3

def build_ring(params):
    names = []
    for j in params:
        names += ['s%d' % j, 't%d' % j]
    names += ['u']              # Rabinowitsch variable: u * (product of edge norms) = 1
    R = PolynomialRing(K, names, order='degrevlex')
    g = R.gens()
    Z = {j: g[2 * i] + g[2 * i + 1] * w for i, j in enumerate(params)}
    Zb = {j: g[2 * i] + g[2 * i + 1] * w**-1 for i, j in enumerate(params)}
    return R, Z, Zb

def to_poly(form, Z):
    p = 0
    for k, v in form.items():
        if k == 'c':
            p += Kel(v)
        else:
            p += Kel(v) * Z[int(k)]
    return p

def to_poly_bar(form, Zb):
    p = 0
    for k, v in form.items():
        if k == 'c':
            p += Kel(v).conjugate()
        else:
            p += Kel(v).conjugate() * Zb[int(k)]
    return p

def cpoly(R, p):
    return R({m: c.conjugate() for m, c in p.dict().items()})

def edges(P):
    n = len(P)
    return [P[(i + 1) % n] - P[i] for i in range(n)]

def class_polys(cls, R, Z, Zb):
    out = []
    for c in cls:
        forms = [{k: tuple(v) for k, v in f.items()} for f in c['forms']]
        out.append(([R(to_poly(f, Z)) for f in forms], [R(to_poly_bar(f, Zb)) for f in forms]))
    return out

def straight_eq(R, P, Pb, i):
    n = len(P)
    A = P[i] - P[i - 1]; B = P[(i + 1) % n] - P[i]
    Ab = Pb[i] - Pb[i - 1]; Bb = Pb[(i + 1) % n] - Pb[i]
    return R(Ab * B - A * Bb)

def solve_pair(R, X, Y, nx, ny, max_del=3):
    """X, Y: (polys, conj polys). Returns list of non-empty systems."""
    found = []
    PX, PXb = X; PY, PYb = Y
    for m in range(5, min(nx, ny) + 1):
        for DX in itertools.combinations(range(nx), nx - m):
            sx = [straight_eq(R, PX, PXb, i) for i in DX]
            if any(q != 0 and q.is_constant() for q in sx):
                continue
            keepX = [i for i in range(nx) if i not in DX]
            for DY in itertools.combinations(range(ny), ny - m):
                sy = [straight_eq(R, PY, PYb, i) for i in DY]
                if any(q != 0 and q.is_constant() for q in sy):
                    continue
                keepY = [i for i in range(ny) if i not in DY]
                Xr = [PX[i] for i in keepX]; Xrb = [PXb[i] for i in keepX]
                Yr = [PY[i] for i in keepY]; Yrb = [PYb[i] for i in keepY]
                f = edges(Yr); fb = edges(Yrb)
                for orient in ('direct', 'mirror'):
                    if orient == 'direct':
                        e = edges(Xr); eb = edges(Xrb)
                    else:
                        mX = list(reversed(Xrb)); mXb = list(reversed(Xr))
                        e = edges(mX); eb = edges(mXb)
                    for k in range(m):
                        gens = []
                        for i in range(1, m):
                            q = f[(k + i) % m] * e[0] - f[k] * e[i]
                            gens += [q, cpoly(R, q)]
                        gens.append(f[k] * fb[k] - e[0] * eb[0])
                        gens += sx + sy
                        # edges e_0, f_k cannot vanish inside the domain (interior points are interior)
                        gens.append(R.gen(R.ngens() - 1) * (e[0] * eb[0]) * (f[k] * fb[k]) - 1)
                        gens = [g for g in gens if g != 0]
                        I = R.ideal(gens)
                        d = I.dimension()
                        if d < 0:
                            continue
                        found.append({'m': m, 'DX': list(DX), 'DY': list(DY), 'orient': orient,
                                      'shift': k, 'dim': int(d), 'ideal': I})
    return found

def eval_point(R, sol, params):
    vals = []
    for j in params:
        vals += [sol['s%d' % j], sol['t%d' % j]]
    return vals

def qeval(p, vals):
    # p in K[...]; vals in AA
    return sum(emb(c) * prod_pow(vals, m) for m, c in p.dict().items())

def prod_pow(vals, m):
    r = QQbar(1)
    for v, e in zip(vals, m):
        if e:
            r *= QQbar(v)**e
    return r

def convex_status(Pq):
    n = len(Pq); st = []
    for i in range(n):
        a = Pq[i] - Pq[i - 1]; b = Pq[(i + 1) % n] - Pq[i]
        if a == 0 or b == 0:
            st.append('zero-edge'); continue
        v = a.conjugate() * b
        c = AA((v - v.conjugate()) / (2 * Iq)); d = AA((v + v.conjugate()) / 2)
        st.append('strict' if c > 0 else ('reflex' if c < 0 else ('straight' if d > 0 else 'spike')))
    return st

SURVIVORS = [(4, 27), (2, 15), (27, 3), (15, 1), (76, 1), (76, 3), (76, 27), (76, 15)]

def main(types_path, patch_path, out_path, which=None):
    T, verts, rh, eo = pa.load(types_path, patch_path)
    surv = SURVIVORS if which is None else [SURVIVORS[int(x)] for x in which.split(',')]
    report = []
    for (i, j) in surv:
        r = pa.analyze(T[i], T[j], verts, rh, eo)
        assert r['dead'] is None
        cls = r['classes']
        params = sorted(set(int(k) for c in cls for f in c['forms'] for k in f if k != 'c'))
        R, Z, Zb = build_ring(params)
        CP = class_polys(cls, R, Z, Zb)
        entry = {'thin': i, 'thick': j, 'thin_edges': T[i]['edges'], 'thick_edges': T[j]['edges'],
                 'params': params, 'classes': [{'corners': c['corners'], 'count': c['count'],
                                                'forms': c['forms']} for c in cls], 'pairs': []}
        print('== pair', i, j, 'classes', [c['corners'] for c in cls], 'params', params, flush=True)
        for a, b in itertools.combinations(range(len(cls)), 2):
            sols = solve_pair(R, CP[a], CP[b], cls[a]['corners'], cls[b]['corners'])
            rows = []
            for s in sols:
                row = {k: v for k, v in s.items() if k != 'ideal'}
                I = s['ideal']
                if s['dim'] == 0:
                    pts = []
                    for v in I.variety(QQbar):
                        vals = [v[g] for g in R.gens()]
                        if any(x.imag() != 0 for x in vals):
                            continue
                        vals = [AA(x) for x in vals]
                        # weak convexity of every class at this point
                        conv = []
                        for (P, Pb) in CP:
                            Pq = [qeval(R(p), vals) for p in P]
                            conv.append(convex_status(Pq))
                        ok = all(all(x in ('strict', 'straight') for x in st) for st in conv)
                        pts.append({'point': [str(x) for x in vals],
                                    'point_minpolys': [str(x.minpoly()) for x in vals],
                                    'all_classes_weakly_convex': ok, 'angle_status': conv})
                    row['real_points'] = pts
                else:
                    row['groebner_basis'] = [str(g) for g in I.groebner_basis()]
                rows.append(row)
                print('   classes', a, b, {k: row[k] for k in ('m', 'DX', 'DY', 'orient', 'shift', 'dim')},
                      'real pts:', len(row.get('real_points', [])) if s['dim'] == 0 else 'POSDIM',
                      [p['all_classes_weakly_convex'] for p in row.get('real_points', [])], flush=True)
            entry['pairs'].append({'X': a, 'Y': b, 'nonempty_systems': rows})
        report.append(entry)
        json.dump(report, open(out_path, 'w'), indent=1, default=str)
    print('DONE')

if __name__ == '__main__':
    main(*sys.argv[1:5])
