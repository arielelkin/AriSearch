#!/usr/bin/env python3
"""Assemble the generalized-decoration certificate from the pipeline outputs.

Replay (after the pipeline in ammann-two-class-search.md):
  conda run --no-capture-output -n arisearch python3 \
      research/searches/ammann-two-class-summarize.py WORKDIR \
      research/certificates/ammann-two-class-generalized.json

WORKDIR must contain types.json, pairs6.json, survivors.json, pw0..7.json,
gs0..7.json produced by the replay commands.  Groebner bases of
positive-dimensional pairwise systems are dropped (they are regenerated by
the scripts); everything else is copied.
"""
import sys, json, os

def main(wd, out):
    T = json.load(open(os.path.join(wd, 'types.json')))
    P6 = json.load(open(os.path.join(wd, 'pairs6.json')))
    SV = json.load(open(os.path.join(wd, 'survivors.json')))
    cert = {
        'question': 'Decorations of the arrow-marked Penrose rhombs (<=2 interior points per rhomb, '
                    'segments to rhomb vertices / between interior points / diagonals, placed by the '
                    'marking frame) whose faces form <=2 congruence classes (mirror identified) of convex '
                    'polygons with >=5 corners.',
        'decoration_types_per_rhomb': len(T),
        'types_by_npoints': {str(k): sum(1 for t in T if t['npoints'] == k) for k in (0, 1, 2)},
        'pairs_total': len(T) ** 2,
        'stage1_combinatorial_stats_patch6': P6['stats'],
        'stage2_survivors_sector_test_and_patch7_recheck': SV,
        'stage3_pairwise': [], 'stage4_group_search': []}
    for k in range(8):
        pw = json.load(open(os.path.join(wd, 'pw%d.json' % k)))[0]
        cert['stage3_pairwise'].append({
            'thin': pw['thin'], 'thick': pw['thick'], 'params': pw['params'],
            'class_corners': [c['corners'] for c in pw['classes']],
            'class_counts_patch7': [c['count'] for c in pw['classes']],
            'class_vertex_forms': [c['forms'] for c in pw['classes']],
            'nonempty_pairwise_systems': [
                {'X': p['X'], 'Y': p['Y'],
                 'systems': [{kk: s[kk] for kk in ('m', 'DX', 'DY', 'orient', 'shift', 'dim')} |
                             ({'real_points': len(s['real_points'])} if 'real_points' in s else {})
                             for s in p['nonempty_systems']]}
                for p in pw['pairs']]})
        gs = json.load(open(os.path.join(wd, 'gs%d.json' % k)))[0]
        cert['stage4_group_search'].append(gs)
    found = []
    for g in cert['stage4_group_search']:
        for c in g['nonunit_complete_combinations']:
            for p in c.get('real_points', []):
                if p['classes_at_point'] <= 2 and p['all_tiles_weakly_convex']:
                    found.append({'thin': g['thin'], 'thick': g['thick'], 'blocks': c['blocks'],
                                  'point': p['point'], 'minpolys': p['minpolys']})
    cert['positive_dimensional_complete_combinations'] = sum(
        1 for g in cert['stage4_group_search'] for c in g['nonunit_complete_combinations'] if c['dim'] != 0)
    cert['convex_two_class_points'] = found
    json.dump(cert, open(out, 'w'), indent=1)
    print('two-class convex points:', len(found), 'posdim combos:', cert['positive_dimensional_complete_combinations'])
    for f in found:
        print(f['thin'], f['thick'], f['blocks'], [x[:12] for x in f['point']])

if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
