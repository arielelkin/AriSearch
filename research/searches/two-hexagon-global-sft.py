#!/usr/bin/env python3
"""Vertex-star SFT for edge-to-edge trivalent tilings by two convex hexagons.

Conventions (proved to be faithful in
research/lemmas/two-hexagon-global-sft-encoding.md):

* tile corners 0..5 in counter-clockwise order; side i joins corners i, i+1;
  corner i lies between sides i-1 and i.
* honeycomb cells z=(x,y) in the basis e1=(1,0), e2=(1/2,sqrt3/2);
  directions D[j] at angle 60j: (1,0),(0,1),(-1,1),(-1,0),(0,-1),(1,-1).
* slot k of a cell is the honeycomb corner at angle 30+60k; side-slot k joins
  slots k,k+1 and is shared with the neighbour z+D[k+1] (its side-slot k+3).
* placement (t,r,s): slot k carries corner r+s*k; side-slot k carries tile
  side r+k (s=+1) or r-k-1 (s=-1).
* the vertex at slot k of z is shared by z (slot k), z+D[k] (slot k+2),
  z+D[k+1] (slot k+4).  Every honeycomb vertex is slot 0 or slot 1 of exactly
  one cell.

A *type* is the exact combinatorial data: angles (Fractions, degrees) and an
integer length class for each of the 12 sides.  The SFT depends only on it.
"""
from fractions import Fraction as Fr
import itertools, sys, json

D = [(1, 0), (0, 1), (-1, 1), (-1, 0), (0, -1), (1, -1)]


def add(z, d):
    return (z[0] + d[0], z[1] + d[1])


def symbols(ntypes=2):
    return [(t, r, s) for t in range(ntypes) for s in (1, -1) for r in range(6)]


def corner_at(sym, k):
    t, r, s = sym
    return (r + s * k) % 6


def side_at(sym, k):
    t, r, s = sym
    return (r + k) % 6 if s == 1 else (r - k - 1) % 6


class SFT:
    def __init__(self, angles, lclass, ntypes=2):
        # angles[t][i], lclass[t][i]
        self.angles = [[Fr(a) for a in row] for row in angles]
        self.lclass = lclass
        self.syms = symbols(ntypes)
        S = self.syms
        n = len(S)
        self.tab = {}
        for kk in (0, 1):
            allowed = []
            for i, j, l in itertools.product(range(n), repeat=3):
                if self.vertex_ok(S[i], S[j], S[l], kk):
                    allowed.append((i, j, l))
            self.tab[kk] = allowed

    def ang(self, sym, k):
        return self.angles[sym[0]][corner_at(sym, k)]

    def ln(self, sym, k):
        return self.lclass[sym[0]][side_at(sym, k)]

    def vertex_ok(self, a, b, c, k):
        # a at z slot k, b at z+D[k] slot k+2, c at z+D[k+1] slot k+4
        if self.ang(a, k) + self.ang(b, k + 2) + self.ang(c, k + 4) != 360:
            return False
        # edges: z--z+D[k]: side-slot k-1 of z, side-slot k+2 of b
        if self.ln(a, (k - 1) % 6) != self.ln(b, (k + 2) % 6):
            return False
        # z--z+D[k+1]: side-slot k of z, side-slot k+3 of c
        if self.ln(a, k % 6) != self.ln(c, (k + 3) % 6):
            return False
        # z+D[k] -- z+D[k+1]: direction from b to c is D[k+2];
        # side-slot k+1 of b, side-slot k+4 of c
        if self.ln(b, (k + 1) % 6) != self.ln(c, (k + 4) % 6):
            return False
        return True

    # ------------------------------------------------------------------
    def model(self, cells, wrap=None, only=None):
        from ortools.sat.python import cp_model
        m = cp_model.CpModel()
        n = len(self.syms)
        X = {}
        cellset = set(cells)
        for z in cells:
            X[z] = m.NewIntVar(0, n - 1, "x%d_%d" % z)
        def W(z):
            return wrap(z) if wrap else z
        cnt = 0
        for z in cells:
            for k in (0, 1):
                a, b, c = z, W(add(z, D[k])), W(add(z, D[k + 1]))
                if a in cellset and b in cellset and c in cellset:
                    tab = self.tab[k] if only is None else [t for t in self.tab[k] if all(self.syms[i][0] in only for i in t)]
                    m.AddAllowedAssignments([X[a], X[b], X[c]], tab)
                    cnt += 1
        return m, X

    def solve(self, m, X, time=60, workers=8):
        from ortools.sat.python import cp_model
        s = cp_model.CpSolver()
        s.parameters.max_time_in_seconds = time
        s.parameters.num_workers = workers
        st = s.Solve(m)
        if st in (cp_model.OPTIMAL, cp_model.FEASIBLE):
            return "SAT", {z: s.Value(v) for z, v in X.items()}
        if st == cp_model.INFEASIBLE:
            return "UNSAT", None
        return "UNKNOWN", None

    def patch(self, R, time=60, only=None):
        cells = [(x, y) for x in range(-R, R + 1) for y in range(-R, R + 1)
                 if max(abs(x), abs(y), abs(x + y)) <= R]
        m, X = self.model(cells, only=only)
        return self.solve(m, X, time)

    def torus(self, n, s, mm, time=60):
        # lattice generated by (n,0) and (s,mm)
        def wrap(z):
            x, y = z
            q = y // mm
            x -= s * q
            y -= mm * q
            return (x % n, y)
        cells = [(x, y) for x in range(n) for y in range(mm)]
        m, X = self.model(cells, wrap)
        return self.solve(m, X, time)

    def tori(self, maxindex, time=60):
        """Search all period lattices of index <= maxindex.  Returns first SAT."""
        for N in range(1, maxindex + 1):
            for n in range(1, N + 1):
                if N % n:
                    continue
                mm = N // n
                for s in range(n):
                    st, sol = self.torus(n, s, mm, time)
                    if st == "SAT":
                        return (n, s, mm), sol
                    if st == "UNKNOWN":
                        return ("UNKNOWN", n, s, mm), None
        return None, None


def check_torus(sft, lat, sol):
    """Independent re-check of a torus solution (pure Python)."""
    n, s, mm = lat
    def wrap(z):
        x, y = z
        q = y // mm
        return ((x - s * q) % n, y - mm * q)
    S = sft.syms
    for z in sol:
        for k in (0, 1):
            a = S[sol[z]]; b = S[sol[wrap(add(z, D[k]))]]; c = S[sol[wrap(add(z, D[k + 1]))]]
            if not sft.vertex_ok(a, b, c, k):
                return False
    return True


if __name__ == "__main__":
    # self-test: regular hexagon pair
    reg = SFT([[120] * 6, [120] * 6], [[0] * 6, [0] * 6])
    print("regular: triples", len(reg.tab[0]), len(reg.tab[1]))
    lat, sol = reg.tori(1)
    print("regular torus", lat, check_torus(reg, lat, sol))
